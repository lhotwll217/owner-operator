import assert from "node:assert";
import { isInjectedOwnerText, isSessionBoilerplate } from "./session-text.mjs";

assert.equal(isSessionBoilerplate("<recommended_plugins>catalog</recommended_plugins>"), true);
assert.equal(isSessionBoilerplate("  <environment_context>cwd</environment_context>"), true);
assert.equal(isSessionBoilerplate("find the real customer context"), false);
assert.equal(isInjectedOwnerText("<system-reminder>context</system-reminder>"), true);
assert.equal(isInjectedOwnerText("Caveat: The messages below were generated by the user while running local commands."), true);
assert.equal(isInjectedOwnerText("Caveat: this only works on main"), false, "the owner can start a message with Caveat");

process.stdout.write("ok — shared session boilerplate and injected owner text classification\n");
